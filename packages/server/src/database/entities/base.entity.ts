import { PrimaryKey, AutoIncrement, Index, MaxLength, DatabaseField, UUID, uuid } from '@deepkit/type';

/**
 * Base entity with common fields
 * All entities should extend this class
 */
export abstract class BaseEntity {
    /**
     * Primary key - auto-incremented
     */
    id: number & PrimaryKey & AutoIncrement = 0;

    /**
     * Creation timestamp
     */
    createdAt: Date = new Date();

    /**
     * Last update timestamp
     */
    updatedAt: Date = new Date();

    /**
     * Update the updatedAt timestamp
     */
    touch(): void {
        this.updatedAt = new Date();
    }
}

/**
 * Base entity with a caller-assigned string primary key (varchar(36)).
 *
 * Useful when IDs are generated externally (e.g. `crypto.randomUUID()`,
 * deterministic slugs, singleton rows) — subclasses set `id` in their own
 * factory methods.
 *
 * Must live in the framework package so the deepkit-type-compiler can emit
 * a full `__type` arg-intersection for the primary key; written inline in a
 * consumer module it degrades to plain `string` and the ORM loses the PK.
 */
export abstract class BaseStringPKEntity {
    id: string & PrimaryKey & MaxLength<36> & DatabaseField<{ type: 'varchar(36)' }> = '';
    createdAt: Date = new Date();
    updatedAt: Date = new Date();
    touch(): void {
        this.updatedAt = new Date();
    }
}

/**
 * Base entity with UUID primary key
 */
export abstract class BaseUuidEntity {
    /**
     * UUID primary key - automatically generated by Deepkit
     */
    id: UUID & PrimaryKey = uuid();

    /**
     * Creation timestamp
     */
    createdAt: Date = new Date();

    /**
     * Last update timestamp
     */
    updatedAt: Date = new Date();

    /**
     * Update the updatedAt timestamp
     */
    touch(): void {
        this.updatedAt = new Date();
    }
}

/**
 * Soft delete mixin - adds deletedAt field
 */
export interface SoftDeletable {
    deletedAt: Date | null;
}

/**
 * Check if entity is soft-deleted
 */
export function isSoftDeleted(entity: SoftDeletable): boolean {
    return entity.deletedAt !== null;
}
